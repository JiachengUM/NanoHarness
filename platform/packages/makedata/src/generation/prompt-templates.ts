// ═══════════════════════════════════════════════════════════════════════════
// 硬约束 (hard_constraints) 渲染辅助
// ═══════════════════════════════════════════════════════════════════════════

import type { HardConstraint } from '@eval-platform/database/models/scenario-plan'

const CONSTRAINT_TYPE_LABEL: Record<HardConstraint['type'], string> = {
  capability_required: '必须使用的能力',
  capability_excluded: '禁止使用的能力',
  interaction_pattern: '交互模式约束',
  theme: '主题约束',
  difficulty: '难度约束',
  other: '其他约束',
}

/**
 * 渲染硬约束列表 section（用于注入下游 prompt）
 * 若无硬约束，返回空字符串（不影响原 prompt）。
 */
export function buildHardConstraintsSection(hardConstraints?: HardConstraint[]): string {
  if (!hardConstraints || hardConstraints.length === 0) return ''

  const lines = hardConstraints.map((c, i) =>
    `${i + 1}. 【${CONSTRAINT_TYPE_LABEL[c.type] || c.type}】${c.description}`
  ).join('\n')

  return `### ⚠️ 硬性约束（必须严格遵守，违反任一条的场景都应被剔除）

以下约束从用户原始需求中提取，**所有生成的场景/模式都必须严格满足**：

${lines}
`
}

/**
 * 渲染硬约束的设计/校验规则段（用于指导下游生成行为）
 */
export function buildHardConstraintsDesignRule(hardConstraints?: HardConstraint[]): string {
  if (!hardConstraints || hardConstraints.length === 0) return ''

  return `## 硬约束遵循规则（强制）

上方"硬性约束"列表中的每一条都必须在场景模式中得到体现：

- **capability_required（必须使用的能力）**：所有场景必须以该能力为核心测试点。若约束要求"仅使用能力A"，则每个场景的主任务都应是能力A的运用，而非其他能力。
- **capability_excluded（禁止使用的能力）**：所有场景不得涉及该能力。若约束要求"不涉及能力B"，则场景不应混入能力B相关任务。（注：B作为其他任务的自然副产物出现时是否算违反，需根据约束语义判断——约束禁止的是用户主动要求执行B类任务）
- **interaction_pattern（交互模式）**：所有场景的交互结构必须符合该约束。若约束要求"单轮对话"，则不得生成多轮/跨会话场景；若约束要求"至少N次X操作"，则场景复杂度应支撑≥N次X。
- **theme（主题）**：所有场景的主题必须落在该约束范围内。若约束限定主题T，则场景应是主题T涵盖的子领域，而非主题T之外的领域。
- **difficulty（难度）**：场景难度应符合该约束。若约束要求"常见复杂"，则问题应是真实用户高频遇到的，而非冷僻罕见或生造的。

**自检**：设计完每个场景模式后，逐条对照硬约束列表，确认该模式不违反任何一条。若违反，立即剔除并重新设计。`
}
