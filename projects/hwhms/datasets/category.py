# ==================== 辅助函数：快速查询跨域关联 ====================

def get_cross_domain_associations(source_domain: str, target_domain: str) -> Optional[DomainPairAssociations]:
    """
    获取指定垂域对的跨域关联配置

    Args:
        source_domain: 源垂域名称
        target_domain: 目标垂域名称

    Returns:
        DomainPairAssociations 或 None
    """
    for pair in ALL_CROSS_DOMAIN_ASSOCIATIONS:
        if pair.source_domain == source_domain and pair.target_domain == target_domain:
            return pair
    return None


def get_random_association(source_domain: str, target_domain: str) -> Optional[CrossDomainAssociation]:
    """
    随机获取指定垂域对的一个关联

    Args:
        source_domain: 源垂域名称
        target_domain: 目标垂域名称

    Returns:
        CrossDomainAssociation 或 None
    """
    import random

    pair = get_cross_domain_associations(source_domain, target_domain)
    if pair and pair.associations:
        return random.choice(pair.associations)
    return None


def list_all_associations_for_domain(domain_name: str) -> dict[str, list[CrossDomainAssociation]]:
    """
    列出某个垂域作为源域时的所有关联

    Args:
        domain_name: 垂域名称

    Returns:
        字典，key为目标垂域，value为关联列表
    """
    result = {}
    for pair in ALL_CROSS_DOMAIN_ASSOCIATIONS:
        if pair.source_domain == domain_name:
            result[pair.target_domain] = pair.associations
    return result


def list_all_associations_as_target_domain(domain_name: str) -> dict[str, list[CrossDomainAssociation]]:
    """
    列出某个垂域作为目标域时的所有关联

    Args:
        domain_name: 垂域名称

    Returns:
        字典，key为源垂域，value为关联列表
    """
    result = {}
    for pair in ALL_CROSS_DOMAIN_ASSOCIATIONS:
        if pair.target_domain == domain_name:
            result[pair.source_domain] = pair.associations
    return result


