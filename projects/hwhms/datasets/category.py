from pydantic import BaseModel, Field
from typing import Optional


# ==================== 基础数据模型 ====================

class Category(BaseModel):
    """类别模型"""
    name: str = Field(..., title="类别名称", description="类别名称")
    description: str = Field(..., title="类别描述", description="类别的详细定义和描述")
    examples: list[str] = Field(..., title="示例", description="示例问题或指令")
    notices: Optional[list[str]] = Field(default=None, title="注意事项", description="关于该类别定义的注意事项")


class Domain(BaseModel):
    """垂域模型"""
    key: str = Field(..., title="垂域标识", description="垂域的唯一标识符")
    name: str = Field(..., title="垂域名称", description="垂域的中文名称")
    description: str = Field(..., title="垂域描述", description="垂域的详细定义和描述")
    categories: dict[str, Category] = Field(..., title="子类别", description="该垂域下的所有子类别")
    intent_type: Optional[str] = Field(default=None, title="意图类型", description="该垂域的意图类型（如：知识询问、控制指令等）")


class CrossDomainAssociation(BaseModel):
    """跨域关联模型"""
    source_category: str = Field(..., title="源子类", description="第一垂域的子类名称")
    target_category: str = Field(..., title="目标子类", description="第二垂域的子类名称")
    association_reason: str = Field(..., title="关联原因", description="两个子类关联的逻辑和场景描述")


class DomainPairAssociations(BaseModel):
    """垂域对关联配置"""
    source_domain: str = Field(..., title="源垂域", description="第一个垂域名称")
    target_domain: str = Field(..., title="目标垂域", description="第二个垂域名称")
    associations: list[CrossDomainAssociation] = Field(..., title="关联列表", description="该垂域对的所有子类关联")


