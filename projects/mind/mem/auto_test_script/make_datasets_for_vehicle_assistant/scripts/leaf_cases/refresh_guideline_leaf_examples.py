# Guideline used outdated leaf name; align to tag tree when patching.
LEAF_NAME_ALIASES = {
    "一次性语境的不记录": "一次性闲聊不记录",
}


def iter_leaves(node: dict, path: list[str] | None = None):
    path = path or []
    name = node["name"]
    children = node.get("children") or []
    if not children:
        yield name, node.get("description", ""), path + [name]
        return
    for child in children:
        yield from iter_leaves(child, path + [name])


def load_tree_leaves() -> dict[str, str]:
    data = json.loads(TAG_TREE.read_text(encoding="utf-8"))
    root = data["root"]
    return {name: desc for name, desc, _ in iter_leaves(root)}


def patch_guideline(text: str, examples: dict[str, str]) -> tuple[str, int]:
    """Replace 例子 under each leaf `- `name`` block."""
    count = 0
    lines = text.splitlines(keepends=True)
    leaf_set = set(examples)
    i = 0
    while i < len(lines):
        m = re.match(r"^(\s*)- `([^`]+)`\s*\r?\n$", lines[i])
        if not m:
            i += 1
            continue
        name = m.group(2)
        canonical = LEAF_NAME_ALIASES.get(name, name)
        if canonical not in leaf_set:
            i += 1
            continue
        # Next lines should include 详情 then 例子
        j = i + 1
        detail_idx = example_idx = None
        while j < len(lines):
            if re.match(r"^\s*- `", lines[j]):
                break
            if re.match(r"^\s*- 详情：", lines[j]):
                detail_idx = j
            if re.match(r"^\s*- 例子：", lines[j]):
                example_idx = j
                break
            j += 1
        if example_idx is not None:
            indent = re.match(r"^(\s*)", lines[example_idx]).group(1)
            new_line = f"{indent}- 例子：{examples[canonical]}\n"
            if lines[example_idx] != new_line:
                lines[example_idx] = new_line
                count += 1
            if canonical != name:
                lines[i] = lines[i].replace(f"`{name}`", f"`{canonical}`")
        i += 1
    return "".join(lines), count


def main() -> None:
    tree_leaves = load_tree_leaves()
    missing_in_map = sorted(set(tree_leaves) - set(LEAF_EXAMPLES))
    extra_in_map = sorted(set(LEAF_EXAMPLES) - set(tree_leaves))
    if missing_in_map:
        raise SystemExit(f"LEAF_EXAMPLES missing {len(missing_in_map)} tree leaves: {missing_in_map[:20]}...")
    if extra_in_map:
        raise SystemExit(f"LEAF_EXAMPLES has {len(extra_in_map)} names not in tree: {extra_in_map[:20]}...")

    text = GUIDELINE.read_text(encoding="utf-8")
    new_text, n = patch_guideline(text, LEAF_EXAMPLES)
    GUIDELINE.write_text(new_text, encoding="utf-8")
    print(f"Updated {n} leaf 例子 lines in {GUIDELINE.name}")
    print(f"Tree leaves: {len(tree_leaves)}, example map: {len(LEAF_EXAMPLES)}")


if __name__ == "__main__":
    main()
